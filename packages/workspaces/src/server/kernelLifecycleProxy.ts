/**
 * createKernelLifecycleProxyHandler — server-side Next.js API route handler
 * for all kernel control-plane traffic.
 *
 * Security properties:
 *  - Billing gate: POST /kernels fetches Fence /credentials/cdis first;
 *    if that fails, no kernel is ever launched.
 *  - Kernel spec filtering: the browser receives only the names/costs defined in policy.
 *  - REMOTE_USER forwarded on every upstream request — JEG enforces per-user isolation.
 *  - KERNEL_ID_RE validates all kernel IDs before they reach the upstream URL.
 *
 * Token extraction:
 *  Pass getToken to reuse the host app's cookie logic (strongly recommended).
 *  In gen3-vectis: `(req) => getAccessToken(req.headers['cookie'] ?? '') ?? null`
 *  Ambassador performs RS256 verification before any request reaches Next.js.
 *
 * Usage (src/pages/api/workspace/kernel/[...action].ts — generated by bin/init.mjs):
 *   import { createKernelLifecycleProxyHandler } from '@gen3/jupyter-workspaces/server';
 *   import { getAccessToken } from '../../lib/auth/getLoginStatus';
 *   const policy = process.env.KERNEL_SPEC_POLICY ? JSON.parse(process.env.KERNEL_SPEC_POLICY) : {};
 *   export default createKernelLifecycleProxyHandler({
 *     gen3Endpoint: process.env.GEN3_ENDPOINT,
 *     fenceUrl: process.env.FENCE_URL,
 *     kernelSpecPolicy: policy,
 *     getToken: (req) => getAccessToken(req.headers['cookie'] ?? '') ?? null,
 *   });
 *   export const config = { api: { bodyParser: false } };
 */

