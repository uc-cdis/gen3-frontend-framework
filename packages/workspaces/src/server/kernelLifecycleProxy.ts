function errMsg(err: unknown): string {
  return err instanceof Error ? err.message : String(err);
}

interface RouteContext {
  req: NextApiRequest;
  gen3Endpoint: string;
  fenceUrl: string | undefined;
  kernelSpecPolicy: Partial<KernelSpecPolicy>;
  ambassadorHeaders: Record<string, string>;
  /** Unsanitised JWT — use only for non-header contexts (e.g. Fence fetch body). */
  jwt: string;
  username: string;
  sink: (event: BillingEvent) => void;
  idleKillDays: number;
  maxKernelAgeDays: number;
}

/* -------- GET /api/kernelspecs -------- */
async function handleKernelSpecs(
  ctx: RouteContext,
  res: NextApiResponse,
): Promise<void> {
  const upstream = buildAmbassadorUrl(ctx.gen3Endpoint, '/api/kernelspecs');
  try {
    const upRes = await fetch(upstream, {
      method: 'GET',
      headers: ctx.ambassadorHeaders,
    });
    if (!upRes.ok) {
      res
        .status(upRes.status)
        .json({ error: `Gateway ${upRes.status}: ${upRes.statusText}` });
      return;
    }
    const rawSpecs = (await upRes.json()) as RawKernelSpecsResponse;
    res
      .status(200)
      .json(filterAndAnnotateSpecs(rawSpecs, ctx.kernelSpecPolicy));
  } catch {
    res.status(502).json({ error: 'Failed to fetch kernel specs.' });
  }
}

