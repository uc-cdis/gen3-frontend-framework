const KERNEL_ID_RE = /^[a-f0-9-]{8,36}$/i;

type KernelRoute =
  | { type: 'kernelspecs' }
  | { type: 'kernels_list' }
  | { type: 'kernel_launch' }
  | { type: 'kernel_delete'; kernelId: string }
  | { type: 'kernel_passthrough'; kernelPath: string }
  | { type: 'status' }
  | { type: 'reap' };

type SimpleRoute = Exclude<
  KernelRoute,
  { type: 'kernel_delete' | 'kernel_passthrough' }
>;

// Table-driven simple routes: all match /api/{resource} with no kernel ID segment.
const SIMPLE_ROUTES = new Map<string, SimpleRoute>([
  ['GET:status', { type: 'status' }],
  ['POST:reap', { type: 'reap' }],
  ['GET:kernelspecs', { type: 'kernelspecs' }],
  ['GET:kernels', { type: 'kernels_list' }],
  ['POST:kernels', { type: 'kernel_launch' }],
]);

function resolveKernelRoute(
  method: string,
  actionSegments: string[],
): KernelRoute | null {
  const [seg1, seg2] = actionSegments;

  if (!seg2) {
    return SIMPLE_ROUTES.get(`${method}:${seg1}`) ?? null;
  }

  // Routes with a kernel ID segment — validate format before use.
  if (seg1 === 'kernels' && KERNEL_ID_RE.test(seg2)) {
    if (method === 'DELETE') {
      return { type: 'kernel_delete', kernelId: seg2 };
    }
    // GET /api/kernels/{id}/channels or similar (passthrough for WebSocket upgrade info)
    if (method === 'GET') {
      const rest = actionSegments.slice(2).join('/');
      return {
        type: 'kernel_passthrough',
        kernelPath: `/api/kernels/${seg2}/${rest}`,
      };
    }
  }

  return null;
}

