interface FenceCreds {
  key_id: string;
  api_key: string; // pragma: allowlist secret
}

const EMPTY_FENCE_CREDS: FenceCreds = {
  key_id: '',
  api_key: '', // pragma: allowlist secret
};

async function fetchFenceCreds(
  fenceUrl: string,
  jwt: string,
): Promise<FenceCreds> {
  let parsedFenceUrl: URL;
  try {
    parsedFenceUrl = new URL(fenceUrl);
  } catch {
    throw new Error('Fence URL is misconfigured.');
  }
  if (
    parsedFenceUrl.protocol !== 'http:' &&
    parsedFenceUrl.protocol !== 'https:'
  ) {
    throw new Error('Fence URL is misconfigured.');
  }
  try {
    const response = await fetchFence<FenceCreds>(
      {
        endpoint: 'credentials/api',
        method: 'GET',
        headers: {
          Authorization: `Bearer ${jwt}`,
          'Content-Type': 'application/json',
        },
      },
      process.env.NODE_ENV === 'production', // use the FENCE Service if in production
    );
    if (!response?.data?.api_key) {
      console.error('No valid API key found in Fence response');
      return {
        api_key: '', // pragma: allowlist secret
        key_id: '',
      };
    }
    return response.data;
  } catch (error: unknown) {
    if (error instanceof Error) {
      console.error('Error fetching API key from Fence:', error);
    } else {
      console.error('Error fetching API key from Fence');
    }
    return EMPTY_FENCE_CREDS;
  }
}

