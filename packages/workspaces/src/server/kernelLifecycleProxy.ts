/* -------- POST /api/reap — bulk-delete stale/aged kernels -------- */
async function handleReap(
  ctx: RouteContext,
  res: NextApiResponse,
): Promise<void> {
  //  const listUpstream = buildAmbassadorUrl(ctx.gen3Endpoint, '/api/kernels');
  const listUpstream = `${ctx.gen3Endpoint}/api/kernels`;
  let kernelList: Array<{ id: string; name: string; last_activity?: string }> =
    [];
  try {
    const listRes = await fetch(listUpstream, {
      method: 'GET',
      headers: ctx.ambassadorHeaders,
    });

    if (!listRes.ok) {
      res
        .status(listRes.status)
        .json({ error: `Failed to list kernels: ${listRes.status}` });
      return;
    }
    kernelList = (await listRes.json()) as typeof kernelList;
  } catch (err) {
    res.status(502).json({ error: `Kernel list unavailable: ${errMsg(err)}` });
    return;
  }

  const now = Date.now();
  const idleKillMins = ctx.idleKillDays * 24 * 60;
  const maxAgeMins = ctx.maxKernelAgeDays * 24 * 60;
  const reaped: string[] = [];
  const errors: string[] = [];

  for (const kernel of kernelList) {
    if (!KERNEL_ID_RE.test(kernel.id)) continue; // skip any malformed IDs from upstream
    const lastActivity = kernel.last_activity
      ? new Date(kernel.last_activity).getTime()
      : 0;
    const idleMins =
      lastActivity > 0 ? (now - lastActivity) / 60_000 : Infinity;
    if (idleMins <= idleKillMins && idleMins <= maxAgeMins) continue;

    const deleteUpstream = buildAmbassadorUrl(
      ctx.gen3Endpoint,
      `/api/kernels/${encodeURIComponent(kernel.id)}`,
    );
    try {
      await fetch(deleteUpstream, {
        method: 'DELETE',
        headers: ctx.ambassadorHeaders,
      });
      reaped.push(kernel.id);
      ctx.sink({
        username: ctx.username,
        action: 'terminate',
        kernelId: kernel.id,
        costTier: 0,
        timestamp: new Date().toISOString(),
      });
    } catch {
      errors.push(kernel.id);
    }
  }

  res.status(200).json({ reaped, errors });
}

/* -------- POST /api/kernels — launch with Fence cred injection -------- */
async function handleKernelLaunch(
  ctx: RouteContext,
  res: NextApiResponse,
): Promise<void> {
  if (!ctx.fenceUrl) {
    res.status(503).json({ error: 'FENCE_URL is not configured.' });
    return;
  }

  // 1. Fetch per-user S3 credentials from Fence.
  //    If this fails, we return 502 and do NOT launch a kernel.
  let fenceCreds: FenceCreds;
  try {
    fenceCreds = await fetchFenceCreds(ctx.fenceUrl, ctx.jwt);
  } catch (err) {
    res
      .status(502)
      .json({ error: `Storage credentials unavailable: ${errMsg(err)}` });
    return;
  }

  // 2. Read the original launch body from the client.
  const rawBody = await readBody(ctx.req);
  let launchBody: Record<string, unknown> = {};
  try {
    launchBody = JSON.parse(rawBody.toString('utf8')) as Record<
      string,
      unknown
    >;
  } catch {
    // empty or invalid JSON — proceed with empty body
  }

  const kernelSpec = (launchBody.name as string) || '';

  // 3. Inject gen3-fuse credential env vars into the kernel launch body.
  //    JEG forwards these to the kernel pod → init container writes /.gen3/credentials.json
  //    → gen3-fuse sidecar mounts the user's S3 bucket.
  const enrichedBody = {
    ...launchBody,
    env: {
      ...(launchBody.env as Record<string, string>),
      GEN3_API_KEY_ID: fenceCreds.key_id,
      GEN3_API_KEY_SECRET: fenceCreds.api_key, // pragma: allowlist secret
      NAMESPACE: process.env.NAMESPACE || 'jupyter-pods',
      GEN3_ENDPOINT: ctx.gen3Endpoint,
    },
  };

  // 4. Non-blocking billing event (launch intent).
  const launchTimestamp = new Date().toISOString();
  const costTier = ctx.kernelSpecPolicy.costPerHour?.[kernelSpec] ?? 0;
  ctx.sink({
    username: ctx.username,
    action: 'launch',
    kernelSpec,
    costTier,
    timestamp: launchTimestamp,
  });

  // TODO:
  //  BILLING_HOOK: pricing/quota check — runs before kernel is launched.
  //  Replace the resolved value below with an async pricing/quota API call.
  //  Return false here to block launch with a 402 Payment Required.
  //  Example: const approved = await checkQuotaAndPrice({ username, kernelSpec, costTier });
  const billingApproved = true; // TODO: hook pricing gate here
  if (!billingApproved) {
    res
      .status(402)
      .json({ error: 'Kernel launch requires billing authorization.' });
    return;
  }

  // 5. Forward to JEG via Ambassador.
  const upstream = buildAmbassadorUrl(ctx.gen3Endpoint, '/api/kernels');
  let launchRes: Response;
  try {
    launchRes = await fetch(upstream, {
      method: 'POST',
      headers: { ...ctx.ambassadorHeaders, 'Content-Type': 'application/json' },
      body: JSON.stringify(enrichedBody),
    });
  } catch (err) {
    res.status(502).json({ error: `Kernel launch failed: ${errMsg(err)}` });
    return;
  }

  if (!launchRes.ok) {
    res.status(launchRes.status).json({
      error: `Kernel launch failed: ${launchRes.status} ${launchRes.statusText}`,
    });
    return;
  }

  const kernelData = (await launchRes.json()) as Record<string, unknown>;

  // 6. Non-blocking: record kernelId in billing log.
  const kernelId = kernelData?.id as string | undefined;
  if (kernelId) {
    ctx.sink({
      username: ctx.username,
      action: 'launch',
      kernelSpec,
      kernelId,
      costTier,
      timestamp: launchTimestamp,
    });
  }

  res.status(201).json(kernelData);
}

/* -------- DELETE /api/kernels/{id} -------- */
async function handleKernelDelete(
  ctx: RouteContext,
  route: Extract<KernelRoute, { type: 'kernel_delete' }>,
  res: NextApiResponse,
): Promise<void> {
  const upstream = buildAmbassadorUrl(
    ctx.gen3Endpoint,
    `/api/kernels/${encodeURIComponent(route.kernelId)}`,
  );
  try {
    const upRes = await fetch(upstream, {
      method: 'DELETE',
      headers: ctx.ambassadorHeaders,
    });
    // 404 = already gone = success (idempotent terminate)
    if (!upRes.ok && upRes.status !== 404) {
      res.status(upRes.status).json({
        error: `Kernel terminate failed: ${upRes.status} ${upRes.statusText}`,
      });
      return;
    }
  } catch (err) {
    res.status(502).json({ error: `Kernel terminate failed: ${errMsg(err)}` });
    return;
  }

  // Non-blocking billing event (terminate)
  ctx.sink({
    username: ctx.username,
    action: 'terminate',
    kernelId: route.kernelId,
    costTier: 0, // actual cost determined from launch event by billing system
    timestamp: new Date().toISOString(),
  });

  res.status(204).end();
}

