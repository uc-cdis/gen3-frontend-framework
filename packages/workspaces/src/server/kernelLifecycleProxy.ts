interface RawKernelSpecsResponse {
  default: string;
  kernelspecs: Record<
    string,
    {
      name: string;
      spec: {
        display_name: string;
        language: string;
        argv?: string[];
        metadata?: Record<string, unknown>;
      };
      resources?: Record<string, string>;
    }
  >;
}

function filterAndAnnotateSpecs(
  raw: RawKernelSpecsResponse,
  policy: Partial<KernelSpecPolicy>,
): RawKernelSpecsResponse {
  const allowedSpecs = policy.allowedSpecs ?? [];
  const costPerHour = policy.costPerHour ?? {};
  const displayNames = policy.displayNames ?? {};
  const nodeType = policy.nodeType ?? {};

  if (allowedSpecs.length === 0) {
    // No policy configured — return everything unannotated (useful during dev bootstrap)
    return raw;
  }

  const filteredSpecs: RawKernelSpecsResponse['kernelspecs'] = {};

  for (const specName of allowedSpecs) {
    const rawSpec = raw.kernelspecs[specName];
    if (!rawSpec) continue; // JEG doesn't have this spec — skip silently

    filteredSpecs[specName] = {
      ...rawSpec,
      spec: {
        ...rawSpec.spec,
        // Override display_name with our curated name if provided
        display_name: displayNames[specName] ?? rawSpec.spec.display_name,
        // Inject billing metadata into spec.metadata (available to browser)
        metadata: {
          ...rawSpec.spec.metadata,
          costPerHour: costPerHour[specName] ?? 0,
          nodeType: nodeType[specName] ?? 'unknown',
        },
      },
    };
  }

  // Use first allowed spec as default if original default was filtered out
  const filteredDefault = allowedSpecs.includes(raw.default)
    ? raw.default
    : (allowedSpecs[0] ?? '');

  return { default: filteredDefault, kernelspecs: filteredSpecs };
}

/* ------------------------------------------------------------------ */
/*  Body buffering (Next.js bodyParser: false)                          */
/* ------------------------------------------------------------------ */

function readBody(req: NextApiRequest): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const chunks: Buffer[] = [];
    req.on('data', (chunk: Buffer) => chunks.push(chunk));
    req.on('end', () => resolve(Buffer.concat(chunks)));
    req.on('error', reject);
  });
}

