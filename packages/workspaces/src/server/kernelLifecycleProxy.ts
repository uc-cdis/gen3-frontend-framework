/** Kernel spec filtering and cost annotation policy (server-side only). */
export interface KernelSpecPolicy {
  /**
   * Raw JEG kernel spec names that are permitted for this deployment.
   * Only these will be returned to the browser.
   */
  allowedSpecs: string[];
  /**
   * Cost per hour for each spec. 0 = included in base subscription.
   * Injected into the spec as `costPerHour` before returning to browser.
   */
  costPerHour: Record<string, number>;
  /**
   * Human-readable display name per spec (replaces raw JEG spec name).
   * e.g. { "python3_gpu_a100": "Python (GPU A100 — $2.40/hr)" }
   */
  displayNames: Record<string, string>;
  /**
   * Node type label for UI badge.
   * e.g. { "python3_micro": "micro", "python3_gpu_a100": "gpu" }
   */
  nodeType: Record<string, string>;
}

export interface BillingEvent {
  username: string;
  action: 'launch' | 'terminate';
  kernelSpec?: string;
  kernelId?: string;
  costTier: number;
  timestamp: string;
}

export interface KernelLifecycleProxyConfig {
  /**
   * External hostname for Ambassador routing, e.g. "mycommons.example.com"
   * or "localhost:30080" in local dev.
   * Used to build the upstream URL: https://{gen3Endpoint}/lw-workspace/proxy/...
   */
  gen3Endpoint: string | undefined;
  /** Internal URL of the Fence service, e.g. http://fence.fence.svc:80 */
  fenceUrl: string | undefined;
  /** Kernel spec filtering + billing policy (server-side only). */
  kernelSpecPolicy: Partial<KernelSpecPolicy>;
  /**
   * Set to true when JEG is configured and enabled for this deployment.
   * Controlled by ENABLE_JEG=true env var in gen3-vectis.
   * When false (default), all routes except GET /api/status return 503 silently so
   * the UI fails gracefully without error spam.
   */
  jegEnabled?: boolean;
  /**
   * Number of idle days before a kernel is considered stale (for /api/reap).
   * Defaults to 10. Controlled by JEG_IDLE_KILL_DAYS env var.
   */
  idleKillDays?: number;
  /**
   * Maximum kernel age in days regardless of idle state (for /api/reap).
   * Defaults to 15. Controlled by JEG_MAX_KERNEL_AGE_DAYS env var.
   */
  maxKernelAgeDays?: number;
  /**
   * Optional billing event sink. Defaults to structured JSON to stdout (CloudWatch).
   * Swap for DynamoDB, Stripe, etc. without changing any other code.
   * The function MUST NOT block — fire and forget.
   */
  billingSink?: (event: BillingEvent) => void;
  /**
   * Token extractor injected by the host application.
   * In gen3-vectis: `(req) => getAccessToken(req.headers['cookie'] ?? '') ?? null`
   * When omitted a minimal Bearer-header/cookie fallback is used (dev/standalone only).
   * Ambassador has already done RS256 verification — this is extraction only.
   */
  getToken?: (req: NextApiRequest) => string | null;
}

